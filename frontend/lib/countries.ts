export function fallbackCountries(): WooCountry[] {
  const displayNames = new Intl.DisplayNames(["en"], { type: "region" });
  return ISO_COUNTRY_CODES.split(" ").map((code) => ({
    code,
    name: displayNames.of(code) ?? code,
    states: code === "US" ? US_STATES.map(([stateCode, name]) => ({ code: stateCode, name })) : [],
  })).sort((left, right) => left.name.localeCompare(right.name));
}
